import AppKit

/// One saved clipboard: every item, every type, the bytes of each.
struct ClipboardSnapshot {
    var items: [[String: Data]]
}

/// What the app needs from a pasteboard. A protocol so the privacy rules below run against an
/// in-memory pasteboard in tests, never against the user's real clipboard.
protocol ClipboardBoard: AnyObject {
    /// Increases whenever the contents change.
    var changeCount: Int { get }
    /// The name of every type on every item. Reading names is all the privacy check needs; it
    /// does not read any data.
    func typeNames() -> Set<String>
    /// The plain text, if the clipboard holds some.
    func plainText() -> String?
    /// Every item with the data of every type, or nil when that would take more than
    /// `byteLimit` bytes (the clipboard could then not be put back faithfully).
    func snapshot(byteLimit: Int) -> ClipboardSnapshot?
    /// Puts a snapshot back, replacing whatever is there.
    func restore(_ snapshot: ClipboardSnapshot)
    /// Replaces the contents with `text`. `transient` flags it so that clipboard managers leave
    /// it out of their history.
    func replaceWithText(_ text: String, transient: Bool)
}

/// The rules for touching the clipboard.
///
/// The app uses the clipboard only when the user asks for a conversion that needs it (convert
/// clipboard, transliterate, or fixing a selection in an app that will not show it). Then:
/// - Content flagged concealed, transient or auto-generated by whoever put it there (password
///   managers, one-time codes, other utilities' scratch copies) is never read and never
///   converted, and is not touched either.
/// - Text longer than `maxTextLength` characters is ignored: not converted, not kept.
/// - What was on the clipboard before is saved in full (all items, all types) and put back.
enum ClipboardPolicy {
    /// Longest text, in Unicode scalars, that is read for conversion.
    static let maxTextLength = 10_000

    /// The nspasteboard.org markers. Any one of them on any item means "hands off".
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
    ]

    /// Our own marker on the temporary text of a paste (see `ClipboardBoard.replaceWithText`).
    static let transientType = "org.nspasteboard.TransientType"

    /// Whether the clipboard must not be read, converted or overwritten.
    static func isSensitive(_ board: ClipboardBoard) -> Bool {
        !board.typeNames().isDisjoint(with: sensitiveTypes)
    }

    enum Reading: Equatable {
        case text(String)
        /// No text on the clipboard (or an empty string).
        case empty
        /// Flagged concealed, transient or auto-generated. Nothing was read.
        case refusedSensitive
        /// More than `maxTextLength` characters. The text was dropped as soon as it was measured.
        case refusedTooLong
    }

    /// The clipboard's text, if the rules allow it to be used.
    static func readText(_ board: ClipboardBoard) -> Reading {
        if isSensitive(board) { return .refusedSensitive }
        guard let text = board.plainText(), !text.isEmpty else { return .empty }
        return exceedsLimit(text) ? .refusedTooLong : .text(text)
    }

    /// Whether `text` is longer than the limit. Cheap for huge strings: four bytes bound a scalar.
    static func exceedsLimit(_ text: String) -> Bool {
        if text.utf8.count > 4 * maxTextLength { return true }
        return text.unicodeScalars.count > maxTextLength
    }
}

/// The system pasteboard, or a named private one.
final class NSPasteboardBoard: ClipboardBoard {
    private let pasteboard: NSPasteboard

    init(_ pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    var changeCount: Int { pasteboard.changeCount }

    func typeNames() -> Set<String> {
        var names = Set((pasteboard.types ?? []).map(\.rawValue))
        for item in pasteboard.pasteboardItems ?? [] {
            for type in item.types { names.insert(type.rawValue) }
        }
        return names
    }

    func plainText() -> String? {
        pasteboard.string(forType: .string)
    }

    func snapshot(byteLimit: Int) -> ClipboardSnapshot? {
        var total = 0
        var items: [[String: Data]] = []
        for item in pasteboard.pasteboardItems ?? [] {
            var types: [String: Data] = [:]
            for type in item.types {
                guard let data = item.data(forType: type) else { continue }
                total += data.count
                if total > byteLimit { return nil }
                types[type.rawValue] = data
            }
            items.append(types)
        }
        return ClipboardSnapshot(items: items)
    }

    func restore(_ snapshot: ClipboardSnapshot) {
        pasteboard.clearContents()
        let items = snapshot.items.map { types -> NSPasteboardItem in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return item
        }
        if !items.isEmpty { pasteboard.writeObjects(items) }
    }

    func replaceWithText(_ text: String, transient: Bool) {
        pasteboard.clearContents()
        if transient {
            let marker = NSPasteboard.PasteboardType(ClipboardPolicy.transientType)
            pasteboard.declareTypes([.string, marker], owner: nil)
            pasteboard.setString(text, forType: .string)
            pasteboard.setData(Data(), forType: marker)
        } else {
            pasteboard.declareTypes([.string], owner: nil)
            pasteboard.setString(text, forType: .string)
        }
    }
}
