/// Time that only moves when a test says so. Also the `Date` clock of the undo list.
final class ManualScheduler: TimerScheduler {
    private(set) var now: TimeInterval = 5_000
    private var entries: [(id: Int, due: TimeInterval, work: () -> Void)] = []
    private var nextID = 0

    /// The `Date` that goes with `now`.
    var date: Date { Date(timeIntervalSinceReferenceDate: now) }

    /// Timers that are scheduled and not yet fired or cancelled.
    var pendingCount: Int { entries.count }

    @discardableResult
    func schedule(after delay: TimeInterval, _ work: @escaping () -> Void) -> ScheduledTask {
        nextID += 1
        let id = nextID
        entries.append((id, now + max(0, delay), work))
        return Task(scheduler: self, id: id)
    }

    /// Moves time forward, running every timer that falls due on the way, in order.
    func advance(by seconds: TimeInterval) {
        let target = now + seconds
        while let next = entries.filter({ $0.due <= target }).min(by: { $0.due < $1.due }) {
            entries.removeAll { $0.id == next.id }
            now = max(now, next.due)
            next.work()
        }
        now = target
    }

    fileprivate func cancel(_ id: Int) {
        entries.removeAll { $0.id == id }
    }

    private final class Task: ScheduledTask {
        let scheduler: ManualScheduler
        let id: Int
        init(scheduler: ManualScheduler, id: Int) {
            self.scheduler = scheduler
            self.id = id
        }
        func cancel() { scheduler.cancel(id) }
    }
}

/// A pasteboard held in memory.
final class MemoryBoard: ClipboardBoard {
    static let stringType = NSPasteboard.PasteboardType.string.rawValue
    static let htmlType = NSPasteboard.PasteboardType.html.rawValue
    static let concealed = "org.nspasteboard.ConcealedType"
    static let transient = "org.nspasteboard.TransientType"
    static let autoGenerated = "org.nspasteboard.AutoGeneratedType"

    private(set) var items: [[String: Data]] = []
    private(set) var changeCount = 0
    /// How many times the text was read. A refused clipboard must leave this at zero.
    private(set) var textReads = 0
    /// How many times full contents were copied out.
    private(set) var snapshots = 0
    /// Pretends the contents are this many bytes when a snapshot is asked for.
    var pretendSize: Int?

    func set(_ items: [[String: Data]]) {
        self.items = items
        changeCount += 1
    }

    func setText(_ text: String, also types: [String] = []) {
        var item = [Self.stringType: Data(text.utf8)]
        for type in types { item[type] = Data() }
        set([item])
    }

    var text: String? {
        items.lazy.compactMap { $0[Self.stringType] }.first.flatMap { String(data: $0, encoding: .utf8) }
    }

    var typeSet: Set<String> { Set(items.flatMap { $0.keys }) }

    func typeNames() -> Set<String> { typeSet }

    func plainText() -> String? {
        textReads += 1
        return text
    }

    func snapshot(byteLimit: Int) -> ClipboardSnapshot? {
        snapshots += 1
        let size = pretendSize ?? items.reduce(0) { $0 + $1.values.reduce(0) { $0 + $1.count } }
        return size > byteLimit ? nil : ClipboardSnapshot(items: items)
    }

    func restore(_ snapshot: ClipboardSnapshot) {
        set(snapshot.items)
    }

    func replaceWithText(_ text: String, transient: Bool) {
        var item = [Self.stringType: Data(text.utf8)]
        if transient { item[Self.transient] = Data() }
        set([item])
    }
}

