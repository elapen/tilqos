/// Records what `Log` would have written, and puts the global switches back afterwards.
final class LogCapture {
    private(set) var lines: [(level: Log.Level, category: Log.Category, text: String)] = []
    private let previousDiagnostics: Bool

    /// `diagnostics`: whether info and debug lines are on, as the user's setting would make them.
    init(diagnostics: Bool) {
        previousDiagnostics = Log.diagnosticsEnabled
        Log.diagnosticsEnabled = diagnostics
        Log.sink = { [unowned self] level, category, text in
            self.lines.append((level, category, text))
        }
    }

    func stop() {
        Log.sink = nil
        Log.diagnosticsEnabled = previousDiagnostics
    }

    var all: String { lines.map(\.text).joined(separator: "\n") }
}

enum PrivacyTestSupport {
    /// The package root, found from this file.
    static var packageRoot: URL {
        URL(fileURLWithPath: #filePath)
            .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
    }

    /// Every `.swift` file under `Sources/` except the model generator, which is a build tool.
    static func appSources() throws -> [(name: String, text: String)] {
        let root = packageRoot.appendingPathComponent("Sources")
        var found: [(String, String)] = []
        let enumerator = FileManager.default.enumerator(at: root, includingPropertiesForKeys: nil)
        while let url = enumerator?.nextObject() as? URL {
            guard url.pathExtension == "swift", !url.path.contains("/GenModel/") else { continue }
            found.append((url.path.replacingOccurrences(of: root.path + "/", with: ""),
                          try String(contentsOf: url, encoding: .utf8)))
        }
        return found.sorted { $0.0 < $1.0 }
    }

    /// A fix with the given words, made at `time`.
    static func fix(
        _ original: String = "ghbdtn", _ corrected: String = "привет", at time: Date = Date(),
        clipboardBefore: String? = nil
    ) -> AppliedFix {
        AppliedFix(
            kind: clipboardBefore == nil ? .layoutFix : .transliteration,
            clipboardBefore: clipboardBefore,
            replacement: Replacement(deletedText: original, insertText: corrected),
            bundleID: "com.example.editor", time: time,
            originalWord: original, correctedWord: corrected,
            previousLayoutID: nil, strategy: .synthetic, typedWords: [original])
    }
}
